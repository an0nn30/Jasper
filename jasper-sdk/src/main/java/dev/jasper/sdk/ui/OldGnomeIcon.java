package dev.jasper.sdk.ui;

/**
 * Semantic artwork for the classic skins. The host supplies bundled OldGNOME2 images in retro, and
 * desktop icon-theme images with those as fallback in GTK.
 * @since 0.7.4
 */
public enum OldGnomeIcon {
    /** Closed padlock. */
    LOCK,
    /** Open padlock. */
    UNLOCK,
    /** Keyring. */
    KEY,
    /** Directory. */
    FOLDER,
    /** Save document. */
    SAVE,
    /** Search. */
    SEARCH,
    /** Undo history. */
    HISTORY,
    /** Bookmark. */
    BOOKMARK,
    /** Add. */
    ADD,
    /** Remove. */
    REMOVE,
    /** Delete. */
    DELETE,
    /** Copy. */
    COPY,
    /** Paste. */
    PASTE,
    /** Refresh. */
    REFRESH,
    /** Preferences. */
    SETTINGS,
    /** Execute. */
    EXECUTE,
    /** Connect. */
    CONNECT,
    /** Disconnect. */
    DISCONNECT,
    /** Network. */
    NETWORK,
    /** Information. */
    INFO,
    /** Help. */
    HELP,
    /** Close. */
    CLOSE;
}
