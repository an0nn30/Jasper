package dev.jasper.sdk.ui;

/**
 * Semantic icons supplied by Jasper; the host owns the artwork.
 * @since 0.7.4
 */
public enum IconName {
    /** Closed padlock. */
    LOCK,
    /** Open padlock. */
    UNLOCK,
    /** Keyring. */
    KEY,
    /** Directory. */
    FOLDER,
    /** Save document. */
    SAVE,
    /** Search. */
    SEARCH,
    /** Undo history. */
    HISTORY,
    /** Bookmark. */
    BOOKMARK,
    /** Add. */
    ADD,
    /** Remove. */
    REMOVE,
    /** Delete. */
    DELETE,
    /** Copy. */
    COPY,
    /** Paste. */
    PASTE,
    /** Refresh. */
    REFRESH,
    /** Preferences. */
    SETTINGS,
    /** Execute. */
    EXECUTE,
    /** Connect. */
    CONNECT,
    /** Disconnect. */
    DISCONNECT,
    /** Network. */
    NETWORK,
    /** Information. */
    INFO,
    /** Help. */
    HELP,
    /** Close. */
    CLOSE,
    /** File. @since 0.7.5 */
    FILE,
    /** Link. @since 0.7.5 */
    LINK,
    /** Upload. @since 0.7.5 */
    UPLOAD,
    /** Download. @since 0.7.5 */
    DOWNLOAD,
    /** Up. @since 0.7.5 */
    UP,
    /** New Folder. @since 0.7.5 */
    NEW_FOLDER,
    /** Pause. @since 0.7.5 */
    PAUSE,
    /** Resume. @since 0.7.5 */
    RESUME,
    /**
     * Split the current pane.
     * @since 0.7.6
     */
    SPLIT,
    /**
     * Enlarge the current pane to fill its tab.
     * @since 0.7.6
     */
    ZOOM,
    /**
     * A local terminal session.
     * @since 0.7.6
     */
    TERMINAL,
    /**
     * A remote host or server session.
     * @since 0.7.6
     */
    SERVER,
    /** Edit. @since 0.8.2 */
    EDIT,
    /** More. @since 0.8.2 */
    MORE,
    /** Previous. @since 0.8.2 */
    PREVIOUS,
    /** Next. @since 0.8.2 */
    NEXT,
    /** Dropdown. @since 0.8.2 */
    DROPDOWN,
    /** Close hovered. @since 0.8.2 */
    CLOSE_HOVERED,
    /** Match case. @since 0.8.2 */
    MATCH_CASE,
    /** Regex. @since 0.8.2 */
    REGEX,
    /** Search history. @since 0.8.2 */
    SEARCH_HISTORY,
    /** New window. @since 0.8.2 */
    NEW_WINDOW,
    /** Exit. @since 0.8.2 */
    EXIT,
    /** Previous match. @since 0.8.2 */
    PREVIOUS_MATCH,
    /** Next match. @since 0.8.2 */
    NEXT_MATCH;
}
