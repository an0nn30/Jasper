package dev.jasper.sdk.ui;

/**
 * Semantic icons supplied by Jasper. The host selects artwork for the running skin.
 * @since 0.7.4
 */
public enum IconName {
    /** Closed padlock. */
    LOCK,
    /** Open padlock. */
    UNLOCK,
    /** Keyring. */
    KEY,
    /** Directory. */
    FOLDER,
    /** Save document. */
    SAVE,
    /** Search. */
    SEARCH,
    /** Undo history. */
    HISTORY,
    /** Bookmark. */
    BOOKMARK,
    /** Add. */
    ADD,
    /** Remove. */
    REMOVE,
    /** Delete. */
    DELETE,
    /** Copy. */
    COPY,
    /** Paste. */
    PASTE,
    /** Refresh. */
    REFRESH,
    /** Preferences. */
    SETTINGS,
    /** Execute. */
    EXECUTE,
    /** Connect. */
    CONNECT,
    /** Disconnect. */
    DISCONNECT,
    /** Network. */
    NETWORK,
    /** Information. */
    INFO,
    /** Help. */
    HELP,
    /** Close. */
    CLOSE,
    /** File. @since 0.7.5 */
    FILE,
    /** Link. @since 0.7.5 */
    LINK,
    /** Upload. @since 0.7.5 */
    UPLOAD,
    /** Download. @since 0.7.5 */
    DOWNLOAD,
    /** Up. @since 0.7.5 */
    UP,
    /** New Folder. @since 0.7.5 */
    NEW_FOLDER,
    /** Pause. @since 0.7.5 */
    PAUSE,
    /** Resume. @since 0.7.5 */
    RESUME;
}
