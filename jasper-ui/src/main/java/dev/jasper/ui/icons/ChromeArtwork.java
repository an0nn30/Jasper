package dev.jasper.ui.icons;

/**
 * The artwork the native workspace chrome's receivers draw (Enterprise presentation spec 5.2's {@code [chrome] icons}):
 * IntelliJ's New UI originals, or its classic icons where the classic set has the meaning.
 */
public enum ChromeArtwork {
    /** IntelliJ's New UI originals, then the ordinary catalog: the chrome artwork every look drew before the classic set. */
    NEW_UI,
    /** IntelliJ's classic icons for the meanings the classic set has, else the New UI originals, then the catalog. */
    CLASSIC
}
