"""Map the code a range of commits changed to the guides that describe it.

Usage: python3 doc_areas.py <base> [<head>]   (head defaults to HEAD)

Prints, per area, the commits and changed files in base..head and the guides to review, then the current guides
the range itself edited (their authors' wording needs the convention check too). Paths no rule covers are listed
last: decide by hand whether a guide describes them. The rules are first-match, most specific first; extend RULES
when a new module, package or plugin appears.
"""
