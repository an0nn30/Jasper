def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout


def area_of(path):
    for area, prefixes, _ in RULES:
        if any(path.startswith(prefix) for prefix in prefixes):
            return area
    return None


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    base, head = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "HEAD")
    commits = [line.split(" ", 1) for line in git("log", "--no-merges", "--format=%h %s", f"{base}..{head}").splitlines()]
    print(f"{len(commits)} non-merge commit(s) in {base}..{head}\n")
    areas, unmapped, edited_guides, tests = {}, [], [], set()
    for sha, subject in commits:
        for path in git("show", "--name-only", "--format=", sha).splitlines():
            if not path or path == "docs/sdk-reference.html":  # generated: regenerate it, never review it by hand
                continue
            if "/src/test/" in path or "/src/testFixtures/" in path:
                tests.add(path)
                continue
            is_guide = (path.endswith(".md") or path.startswith("tools/sdk-reference/guide/")) and not path.startswith(("docs/superpowers/", "docs/design/", "docs/benchmarks/"))
            if is_guide and "/src/" not in path:
                edited_guides.append((sha, path))
                continue
            area = area_of(path)
            if area is None:
                unmapped.append(path)
                continue
            entry = areas.setdefault(area, {"commits": {}, "files": set()})
            entry["commits"][sha] = subject
            entry["files"].add(path)
    for area, prefixes, guides in RULES:
        if area not in areas:
            continue
        entry = areas[area]
        print(f"## {area}: {len(entry['files'])} file(s)")
        for sha, subject in entry["commits"].items():
            print(f"   {sha} {subject}")
        print("   guides: " + ", ".join(guides) + "\n")
    if edited_guides:
        print("## current guides the range edited (check their wording against the conventions)")
        for path in sorted({p for _, p in edited_guides}):
            print("   " + path)
        print()
    if tests:
        print(f"## tests only: {len(tests)} file(s) (read them for the behaviour they pin; they need no guide)\n")
    if unmapped:
        print("## unmapped paths (decide by hand)")
        for path in sorted(set(unmapped)):
            print("   " + path)


main()
